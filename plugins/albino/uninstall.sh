#!/usr/bin/env bash
# Removes the albino plugin. Run by the root uninstall.sh. Each step undoes one
# step of install.sh and reports "Already removed." when there is nothing to undo.
set -euo pipefail
# shellcheck source=../../scripts/install-lib.sh
source "$MYAGENTS_DIR/scripts/install-lib.sh"

PLUGIN_NAME="albino"
PLUGIN_ID="${PLUGIN_NAME}@${MYAGENTS_MARKETPLACE}"
PLUGIN_SRC="$MYAGENTS_DIR/plugins/$PLUGIN_NAME"

CLAUDE_PLUGINS_DIR="$HOME/.claude/plugins"
CURSOR_PLUGIN_LINK="$HOME/.cursor/plugins/local/$PLUGIN_NAME"

CODEX_HOME="${CODEX_HOME:-$HOME/.codex}"
CODEX_PROMPTS_DIR="$CODEX_HOME/prompts"
CODEX_AGENTS_DIR="$CODEX_HOME/agents"
CODEX_SKILLS_DIR="$CODEX_HOME/skills"

need python3

# Claude Code: drop every entry install.sh wrote, plus a statusLine that points
# at the plugin's statusline script (set by the /statusline command), since it
# stops working once ~/.myagents is gone. Prints whether anything changed.
if has_claude_code; then
  if quietly python3 - \
      "$PLUGIN_SRC" "$MYAGENTS_MARKETPLACE" "$PLUGIN_ID" \
      "$CLAUDE_PLUGINS_DIR/known_marketplaces.json" \
      "$CLAUDE_PLUGINS_DIR/installed_plugins.json" \
      "$HOME/.claude/settings.json" \
      <<'PY'
import json, os, sys

plugin_src, mkt_name, plugin_id, known_path, installed_path, settings_path = sys.argv[1:7]
changed = False

def load(path):
    try:
        with open(path) as f:
            return json.load(f)
    except FileNotFoundError:
        return None

def save(path, data):
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        json.dump(data, f, indent=2)
        f.write("\n")
    os.replace(tmp, path)

def drop(container, key):
    global changed
    if isinstance(container, dict) and key in container:
        del container[key]
        changed = True
        return True
    return False

def drop_from(parent, section, key):
    # Removes the section too when this leaves it empty.
    removed = drop(parent.get(section), key)
    if removed and parent[section] == {}:
        del parent[section]
    return removed

known = load(known_path)
if drop(known, mkt_name):
    save(known_path, known)

installed = load(installed_path)
if installed and drop(installed.get("plugins"), plugin_id):
    save(installed_path, installed)

settings = load(settings_path)
if settings is not None:
    touched = drop_from(settings, "enabledPlugins", plugin_id)
    touched = drop_from(settings, "extraKnownMarketplaces", mkt_name) or touched
    command = (settings.get("statusLine") or {}).get("command", "")
    if isinstance(command, str) and command.startswith(plugin_src + "/"):
        touched = drop(settings, "statusLine") or touched
    if touched:
        save(settings_path, settings)

print("removed" if changed else "absent")
PY
  then
    rm -rf "$CLAUDE_PLUGINS_DIR/data/$PLUGIN_NAME-$MYAGENTS_MARKETPLACE"
    if [ "$quiet_output" = "removed" ]; then
      ok "Claude Code" "Removed. Restart open sessions to unload it."
    else
      ok "Claude Code" "Already removed."
    fi
  else
    fail "Claude Code" "Could not update the settings in ~/.claude/. Check that the JSON files there are valid."
  fi
fi

if has_cursor; then
  if [ -L "$CURSOR_PLUGIN_LINK" ]; then
    rm -f "$CURSOR_PLUGIN_LINK"
    ok "Cursor" "Removed. Run 'Developer: Reload Window' to unload it."
  else
    ok "Cursor" "Already removed."
  fi
fi

# Codex: remove the plugin and marketplace, then the command skills and agents
# the generators wrote. Their marker line keeps hand-written files untouched.
if has_codex; then
  removed=false
  codex_failed=false
  if codex_has_marketplace "$MYAGENTS_MARKETPLACE"; then
    if quietly codex plugin remove "$PLUGIN_ID" && quietly codex plugin marketplace remove "$MYAGENTS_MARKETPLACE"; then
      removed=true
    else
      fail "Codex" "Could not remove $PLUGIN_NAME."
      codex_failed=true
    fi
  fi
  for skill in "$CODEX_SKILLS_DIR"/albino-command-*/; do
    if grep -qF "<!-- Generated by scripts/gen-codex-command-skills.sh." "$skill/SKILL.md" 2>/dev/null; then
      rm -rf "$skill"
      removed=true
    fi
  done
  for agent in "$CODEX_AGENTS_DIR"/*.toml; do
    if [ -f "$agent" ] && head -n 1 "$agent" | grep -qF "# Generated by scripts/gen-codex-agents.sh."; then
      rm -f "$agent"
      removed=true
    fi
  done
  for link in "$CODEX_PROMPTS_DIR"/*.md; do
    [ -L "$link" ] || continue
    case "$(readlink "$link")" in "$PLUGIN_SRC"/commands/*) rm -f "$link" ;; esac
  done
  if [ "$codex_failed" = true ]; then
    :
  elif [ "$removed" = true ]; then
    ok "Codex" "Removed. Restart Codex to unload it."
  else
    ok "Codex" "Already removed."
  fi
fi

finish
