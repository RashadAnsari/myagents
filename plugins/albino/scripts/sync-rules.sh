#!/usr/bin/env bash
set -euo pipefail

# Cursor loads the plugin's rules/*.mdc files directly, but Claude Code and
# Codex cannot load rules from a plugin. This script projects every rules/*.mdc
# file into the places they read instead, so the .mdc files stay the single
# source of truth, and marks each copy as albino's. rules/session-start.mdc is
# skipped: the session-start hook already delivers that text on the other two
# platforms.
#
#   claude: one ~/.claude/rules/albino-<name>.md file per rule <name>.mdc. A rule with
#           Cursor globs gets the same patterns as Claude Code paths.
#   codex:  one block between albino markers in ~/.codex/AGENTS.md, holding
#           every rule. Text outside the markers is never touched.
#
# Usage: sync-rules.sh install|uninstall claude|codex <target>
#   <target> is the rules directory for claude and the AGENTS.md file for codex.
# Prints "changed" or "unchanged". Files and blocks it writes carry an albino
# marker, so it never touches rules or text the user wrote.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RULES_DIR="$SCRIPT_DIR/../rules"

if [ $# -ne 3 ]; then
  echo "Usage: sync-rules.sh install|uninstall claude|codex <target>" >&2
  exit 2
fi

python3 - "$RULES_DIR" "$@" <<'PY'
import os
import pathlib
import re
import sys

rules_dir, action, platform, target = sys.argv[1:5]
target = pathlib.Path(os.path.expanduser(target))
if action not in ("install", "uninstall"):
    sys.exit(f"Unknown action: {action}")

CURSOR_ONLY = {"session-start.mdc"}
CLAUDE_MARKER = "<!-- Generated by the albino installer from rules/{}. Edits are overwritten. -->"
CLAUDE_MARKER_PREFIX = "<!-- Generated by the albino installer from rules/"
BEGIN = "<!-- albino:rules:begin (written by the albino installer; edits are overwritten) -->"
END = "<!-- albino:rules:end -->"
BLOCK = re.compile(r"<!-- albino:rules:begin[^\n]*\n.*?<!-- albino:rules:end -->\n?", re.S)


def parse(path):
    text = path.read_text()
    if not text.startswith("---\n"):
        return {}, text.strip()
    end = text.find("\n---\n", 3)
    if end == -1:
        return {}, text.strip()
    meta = {}
    for line in text[4:end].splitlines():
        if ":" in line:
            key, value = line.split(":", 1)
            meta[key.strip()] = value.strip().strip("\"'")
    return meta, text[end + 5 :].strip()


def rules():
    found = []
    for path in sorted(pathlib.Path(rules_dir).glob("*.mdc")):
        if path.name in CURSOR_ONLY:
            continue
        meta, body = parse(path)
        if not body:
            sys.exit(f"{path.name} has no body.")
        scoped = meta.get("alwaysApply", "").lower() != "true" and meta.get("globs")
        found.append((path, meta.get("globs") if scoped else "", body))
    return found


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text)
    os.replace(tmp, path)


def is_ours(path):
    try:
        return CLAUDE_MARKER_PREFIX in path.read_text()
    except OSError:
        return False


changed = False

if platform == "claude":
    wanted = {}
    if action == "install":
        for path, globs, body in rules():
            head = f"---\npaths: {globs}\n---\n\n" if globs else ""
            wanted["albino-" + path.stem + ".md"] = f"{head}{CLAUDE_MARKER.format(path.name)}\n\n{body}\n"
    for name, text in wanted.items():
        dest = target / name
        if dest.exists() and not is_ours(dest):
            sys.exit(f"{dest} exists and was not written by albino.")
        if not dest.exists() or dest.read_text() != text:
            write(dest, text)
            changed = True
    # Drop what this script wrote for rules that no longer exist, or every
    # albino rule on uninstall.
    for dest in sorted(target.glob("albino-*.md")) if target.is_dir() else []:
        if dest.name not in wanted and is_ours(dest):
            dest.unlink()
            changed = True

elif platform == "codex":
    current = target.read_text() if target.exists() else ""
    match = BLOCK.search(current)
    rest = current
    if match:
        before = current[: match.start()].rstrip("\n")
        after = current[match.end() :].lstrip("\n")
        rest = before + ("\n\n" if before and after else "") + after
        if before and not after:
            rest += "\n"
    new = current if not match else rest
    if action == "install":
        parts = []
        for path, globs, body in rules():
            if globs:
                body = f"Applies when working on files matching: {globs}\n\n{body}"
            parts.append(body)
        if parts:
            block = BEGIN + "\n\n" + "\n\n".join(parts) + "\n\n" + END + "\n"
            new = (rest.rstrip("\n") + "\n\n" if rest.strip() else "") + block
    if new != current:
        changed = True
        if new.strip():
            write(target, new)
        else:
            # The file held only the albino block, so the installer created it.
            target.unlink()

else:
    sys.exit(f"Unknown platform: {platform}")

print("changed" if changed else "unchanged")
PY
